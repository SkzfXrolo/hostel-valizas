function toBlock(obj) {
  return (
    '\n' +
    Object.entries(obj)
      .map(([k, v]) => `    '${k}': ${JSON.stringify(v)},`)
      .join('\n') +
    '\n'
  )
}

const markers = {
  es: "'home.cta.write': 'Escribinos ahora',",
  en: "'home.cta.write': 'Message us now',",
  pt: "'home.cta.write': 'Escreva agora',",
}

for (const [lang, marker] of Object.entries(markers)) {
  if (!s.includes(marker)) throw new Error('missing ' + lang)
  s = s.replace(marker, marker + toBlock(extra[lang]))
}

fs.writeFileSync(path, s)
console.log('ok')
